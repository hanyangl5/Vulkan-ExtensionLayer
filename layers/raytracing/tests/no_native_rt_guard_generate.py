"""Generate the test guard's typed stubs and pinned Vulkan/SPIR-V tables.

This is a development tool, not a build dependency. Pass the exact SDK registry
and SPIR-V grammar used by the build; commit the resulting header/include files.
"""

import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET


def rt_extension(name):
    return any(part in name for part in ("ray_tracing", "ray_query", "acceleration_structure", "opacity_micromap", "displacement_micromap"))


def rt_instruction(name):
    return name == "OpTraceNV" or any(part in name for part in ("Ray", "AccelerationStructure", "HitObject", "ReportIntersection", "IgnoreIntersection", "ExecuteCallable", "ReorderThread"))


def generate(registry_path, grammar_path, output):
    registry = ET.parse(registry_path).getroot()
    grammar = json.loads(grammar_path.read_text(encoding="utf-8"))
    extensions = [e for e in registry.findall("./extensions/extension") if e.get("supported") != "disabled" and rt_extension(e.get("name"))]
    extension_names = sorted({e.get("name") for e in extensions})
    commands = {c.get("name") or c.findtext("./proto/name"): c for c in registry.findall("./commands/command")}
    command_names = sorted({c.get("name") for e in extensions for c in e.findall("./require/command")})
    type_names = {t.get("name") for e in extensions for t in e.findall("./require/type")}
    beta_types = {t.get("name") for e in extensions if e.get("provisional") == "true" for t in e.findall("./require/type")}
    feature_entries = []
    property_entries = []
    for t in registry.findall("./types/type"):
        name = t.get("name")
        if name not in type_names or t.get("category") != "struct" or not name.startswith("VkPhysicalDevice"):
            continue
        members = t.findall("member")
        stype = next((m.get("values") for m in members if m.findtext("name") == "sType"), None)
        if not stype:
            continue
        if "Features" in name:
            for m in members:
                if m.findtext("type") == "VkBool32":
                    feature_entries.append((stype, name, m.findtext("name")))
        elif "Properties" in name and len(members) > 2:
            property_entries.append((stype, name, members[2].findtext("name")))
    capabilities = set()
    models = set()
    known_ops = sorted({i["opcode"] for i in grammar["instructions"]})
    forbidden_ops = sorted({i["opcode"] for i in grammar["instructions"] if rt_instruction(i["opname"])})
    for kind in grammar["operand_kinds"]:
        if kind["kind"] == "Capability":
            capabilities.update(int(v["value"]) for v in kind["enumerants"] if rt_instruction(v["enumerant"]) or "InvocationReorder" in v["enumerant"])
        if kind["kind"] == "ExecutionModel":
            models.update(int(v["value"]) for v in kind["enumerants"] if any(p in v["enumerant"] for p in ("RayGeneration", "Intersection", "AnyHit", "ClosestHit", "Miss", "Callable")))
    header = ["/* Copyright 2026 The Khronos Group Inc.", " * SPDX-License-Identifier: Apache-2.0", " * Generated by no_native_rt_guard_generate.py; do not edit tables by hand.", f" * Vulkan registry SHA256: {hashlib.sha256(registry_path.read_bytes()).hexdigest()}", f" * SPIR-V grammar SHA256: {hashlib.sha256(grammar_path.read_bytes()).hexdigest()}", " */", "#ifndef VKRT_NO_NATIVE_RT_GUARD_REGISTRY_H", "#define VKRT_NO_NATIVE_RT_GUARD_REGISTRY_H", ""]
    header += ["static const char *const guard_rt_extensions[] = {"]
    header += [f'    "{name}",' for name in extension_names]
    header += ["};", "struct guard_feature_field { VkStructureType type; size_t offset; };", "static const struct guard_feature_field guard_rt_feature_fields[] = {"]
    for stype, name, member in feature_entries:
        if name in beta_types: header += ["#ifdef VK_ENABLE_BETA_EXTENSIONS"]
        header += [f"    {{{stype}, offsetof({name}, {member})}},"]
        if name in beta_types: header += ["#endif"]
    header += ["};", "struct guard_property_tail { VkStructureType type; size_t offset, size; };", "static const struct guard_property_tail guard_rt_property_tails[] = {"]
    for stype, name, member in property_entries:
        if name in beta_types: header += ["#ifdef VK_ENABLE_BETA_EXTENSIONS"]
        header += [f"    {{{stype}, offsetof({name}, {member}), sizeof({name}) - offsetof({name}, {member})}},"]
        if name in beta_types: header += ["#endif"]
    header += ["};"]
    for name, values in (("capabilities", sorted(capabilities)), ("models", sorted(models)), ("opcodes", forbidden_ops), ("known_opcodes", known_ops)):
        header += [f"static const uint32_t guard_{name}[] = {{"]
        header += ["    " + ", ".join(str(v) for v in values[start:start + 16]) + "," for start in range(0, len(values), 16)]
        header += ["};"]
    header += ["", "#endif", ""]
    (output / "no_native_rt_guard_registry.h").write_text("\n".join(header), encoding="utf-8")
    native = ["/* Copyright 2026 The Khronos Group Inc.", " * SPDX-License-Identifier: Apache-2.0", " * Generated typed native RT rejection stubs. */", ""]
    for name in command_names:
        command = commands[name]
        while command.get("alias"):
            command = commands[command.get("alias")]
        result = command.findtext("./proto/type")
        params = command.findall("param")
        declaration = ", ".join("".join(p.itertext()).strip() for p in params)
        native += [f"static VKAPI_ATTR {result} VKAPI_CALL guard_{name}({declaration}) {{"]
        native += [f"    (void){p.findtext('name')};" for p in params]
        native += [f'    guard_reject("native_entrypoint", "{name}");']
        if result == "void":
            native += ["    _Exit(86); /* A forbidden void call cannot report VkResult. */"]
        elif result == "VkResult":
            native += ["    return VK_ERROR_FEATURE_NOT_PRESENT;"]
        else:
            native += ["    return 0;"]
        native += ["}", ""]
    native += ["static PFN_vkVoidFunction guard_native_proc(const char *name) {"]
    native += [f'    if (!strcmp(name, "{name}")) return (PFN_vkVoidFunction)guard_{name};' for name in command_names]
    native += ["    return NULL;", "}", ""]
    (output / "no_native_rt_guard_native.inc").write_text("\n".join(native), encoding="utf-8")
    print(f"Generated {len(command_names)} native stubs, {len(feature_entries)} feature fields and {len(forbidden_ops)} SPIR-V opcodes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--grammar", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path(__file__).parent)
    args = parser.parse_args()
    generate(args.registry, args.grammar, args.output)
